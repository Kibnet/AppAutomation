    private static string GenerateCopiedValueStatement(
        RecordedStep step,
        string propertyName,
        IReadOnlyDictionary<Guid, string> copiedValueVariables,
        GridRowVariableNames rowVariables,
        SpinnerKeyVariables spinnerKeyVariables)
    {
        if (step.CopiedValueId is not { } copiedValueId
            || !copiedValueVariables.TryGetValue(copiedValueId, out var variableName))
        {
            throw new InvalidOperationException("Copied value definition was not validated.");
        }

        var valueExpression = GenerateValueExpression(step, propertyName, rowVariables, spinnerKeyVariables);
        return $"var {variableName} = {valueExpression} ?? string.Empty;{Environment.NewLine}await Page.CopyTextToClipboardAsync({variableName});";
    }

    private static string GenerateValueExpression(
        RecordedStep step,
        string propertyName,
        GridRowVariableNames rowVariables,
        SpinnerKeyVariables spinnerKeyVariables)
    {
        var control = $"Page.{propertyName}";
        return step.ValueAccessorKind switch
        {
            RecorderValueAccessorKind.NumericValue when step.Control.ControlType == UiControlType.MultiItemControlCollection =>
                $"{GenerateKeyedSpinnerExpression(step.RepeatedItemKey, control, spinnerKeyVariables)}.Value",
            RecorderValueAccessorKind.IsEnabled when step.Control.ControlType == UiControlType.MultiItemControlCollection =>
                $"{GenerateKeyedSpinnerExpression(step.RepeatedItemKey, control, spinnerKeyVariables)}.IsEnabled",
            RecorderValueAccessorKind.Text when step.Control.ControlType == UiControlType.Button =>
                $"global::AppAutomation.Abstractions.UiControlText.Read({control})",
            RecorderValueAccessorKind.Text => $"{control}.Text",
            RecorderValueAccessorKind.NumericText when step.Control.ControlType == UiControlType.TextBox =>
                $"NumericDisplayValueReader.Read({control})",
            RecorderValueAccessorKind.SelectedItemText when step.Control.ControlType == UiControlType.SearchPicker =>
                $"{control}.SelectedItemText",
            RecorderValueAccessorKind.SelectedItemText when step.Control.ControlType == UiControlType.ListBox =>
                $"((global::AppAutomation.Abstractions.ISelectableListBoxControl){control}).SelectedItemText",
            RecorderValueAccessorKind.SelectedItemText => $"{control}.SelectedItem?.Text",
            RecorderValueAccessorKind.SelectedItems => $"{control}.SelectedItems",
            RecorderValueAccessorKind.NumericValue => $"{control}.Value",
            RecorderValueAccessorKind.SelectedDate => $"{control}.SelectedDate",
            RecorderValueAccessorKind.SelectedTime => $"{control}.SelectedTime",
            RecorderValueAccessorKind.Color => $"{control}.Color",
            RecorderValueAccessorKind.IsChecked => $"{control}.IsChecked",
            RecorderValueAccessorKind.IsToggled => $"{control}.IsToggled",
            RecorderValueAccessorKind.IsSelected when step.Control.ControlType == UiControlType.RadioButton =>
                $"{control}.IsChecked",
            RecorderValueAccessorKind.IsSelected => $"{control}.IsSelected",
            RecorderValueAccessorKind.IsExpanded => $"{control}.IsExpanded",
            RecorderValueAccessorKind.IsEnabled => $"{control}.IsEnabled",
            RecorderValueAccessorKind.IsReadOnly => $"{control}.IsReadOnly",
            RecorderValueAccessorKind.GridCellText or RecorderValueAccessorKind.GridCellValue =>
                GenerateGridCellExpression(step, control, rowVariables),
            _ => throw new InvalidOperationException(
                $"Value accessor '{step.ValueAccessorKind}' is not supported for {step.Control.ControlType}.")
        };
    }

    private static string GenerateKeyedSpinnerExpression(
        string? itemKey,
        string control,
        SpinnerKeyVariables spinnerKeyVariables)
    {
        if (string.IsNullOrWhiteSpace(itemKey))
        {
            throw new InvalidOperationException("A multi-item Spinner check requires a stable item key.");
        }

        return $"{control}.ResolveSpinner({spinnerKeyVariables.FormatKey(control, itemKey)}, 5000)";
    }

    private static string GenerateGridCellExpression(
        RecordedStep step,
        string control,
        GridRowVariableNames rowVariables)
    {
        if (!HasNamedGridRow(step))
        {
            return $"GridValueReader.ReadCellText({control}, {FormatInt(step.RowIndex)}, {FormatInt(step.ColumnIndex)})";
        }

        var methodName = step.ValueAccessorKind == RecorderValueAccessorKind.GridCellValue
            ? step.ValueKind switch
            {
                RecorderValueKind.Number => "ReadCellNumber",
                RecorderValueKind.Date => "ReadCellDate",
                RecorderValueKind.Time => "ReadCellTime",
                RecorderValueKind.Boolean => "ReadCellBoolean",
                _ => "ReadCellText"
            }
            : "ReadCellText";
        return $"GridValueReader.{methodName}({control}, {FormatGridRowSelector(step, rowVariables)}, {FormatGridTargetColumn(step)})";
    }

    private static string FormatExpectedLiteral(RecordedStep step)
    {
        return step.ValueKind switch
        {
            RecorderValueKind.Text or RecorderValueKind.Color or RecorderValueKind.GridCellText =>
                $"\"{EscapeString(step.StringValue ?? string.Empty)}\"",
            RecorderValueKind.Number => FormatDouble(step.DoubleValue),
            RecorderValueKind.Boolean => FormatBoolean(step.BoolValue),
            RecorderValueKind.Date => FormatNullableDate(step.DateValue, step.DateExpression),
            RecorderValueKind.Time => FormatNullableTimeSpan(step.TimeValue),
            RecorderValueKind.StringSet => FormatStringValues(step.StringValues),
            _ => throw new InvalidOperationException($"Literal value kind '{step.ValueKind}' is not supported.")
        };
    }

    internal static void AppendIndentedBlock(StringBuilder builder, string block, string indent)
    {
        var normalized = block.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n');
        foreach (var line in normalized.Split('\n'))
        {
            builder.Append(indent).AppendLine(line);
        }
    }

