    internal const string RecorderGeneratedMarker = "// <auto-generated by AppAutomation Recorder />";
    internal const string AutosaveDestinationMarkerPrefix = "// AppAutomation recorder autosave destination: ";
    internal static string GeneratePagePartial(
        AuthoringTargetConfiguration target,
        ScannedClassInfo pageClass,
        IReadOnlyList<ExistingControlInfo> controls,
        string? autosaveDestinationId)
    {
        var builder = new StringBuilder();
        builder.AppendLine(RecorderGeneratedMarker);
        AppendAutosaveDestinationMarker(builder, autosaveDestinationId);
        builder.AppendLine("using AppAutomation.Abstractions;");
        builder.AppendLine();
        builder.Append("namespace ").Append(target.PageNamespace).AppendLine(";");
        builder.AppendLine();

        foreach (var control in controls)
        {
            builder.AppendLine(GenerateUiControlAttribute(control));
        }

        builder.Append(pageClass.ModifiersText)
            .Append(" partial class ")
            .Append(target.PageClassName)
            .AppendLine();
        builder.AppendLine("{");
        builder.AppendLine("}");
        return builder.ToString();
    }

    internal static string GenerateScenarioPartial(
        AuthoringTargetConfiguration target,
        ScannedClassInfo scenarioClass,
        string methodName,
        IReadOnlyList<string> renderedStatements,
        bool containsAssertions,
        bool requiresAsync,
        bool containsRelativeDates,
        bool isAutosave,
        string? autosaveDestinationId,
        string? autosaveStateMarker)
    {
        var builder = new StringBuilder();
        builder.AppendLine(RecorderGeneratedMarker);
        AppendAutosaveDestinationMarker(builder, autosaveDestinationId);
        if (!string.IsNullOrWhiteSpace(autosaveStateMarker))
        {
            builder.AppendLine(autosaveStateMarker);
        }
        builder.AppendLine("using AppAutomation.Abstractions;");
        if (containsRelativeDates)
        {
            builder.AppendLine("using System;");
        }

        if (requiresAsync)
        {
            builder.AppendLine("using System.Threading.Tasks;");
        }

        if (containsAssertions)
        {
            builder.AppendLine("using TUnit.Assertions;");
            builder.AppendLine("using TUnit.Assertions.Extensions;");
        }

        builder.AppendLine("using TUnit.Core;");
        builder.AppendLine();
        builder.Append("namespace ").Append(target.ScenarioNamespace).AppendLine(";");
        builder.AppendLine();
        if (isAutosave)
        {
            builder.AppendLine("// AppAutomation recorder autosave recovery file.");
            builder.AppendLine("// This file is overwritten while the recorder session is running.");
            builder.AppendLine();
        }

        builder.Append(scenarioClass.ModifiersText)
            .Append(" partial class ")
            .Append(target.ScenarioClassName)
            .Append(scenarioClass.TypeParameterListText)
            .AppendLine();
        builder.AppendLine("{");
        builder.AppendLine("    [Test]");
        builder.AppendLine("    [NotInParallel(DesktopUiConstraint)]");
        builder.Append("    public ");
        if (requiresAsync)
        {
            builder.Append("async Task ");
        }
        else
        {
            builder.Append("void ");
        }

        builder.Append(methodName).AppendLine("()");
        builder.AppendLine("    {");
        foreach (var statement in renderedStatements)
        {
            RecorderStatementEmitter.AppendIndentedBlock(builder, statement, "        ");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendAutosaveDestinationMarker(StringBuilder builder, string? autosaveDestinationId)
    {
        if (!string.IsNullOrWhiteSpace(autosaveDestinationId))
        {
            builder.Append(AutosaveDestinationMarkerPrefix).AppendLine(autosaveDestinationId);
        }
    }

    private static string GenerateUiControlAttribute(ExistingControlInfo control)
    {
        var builder = new StringBuilder();
        builder.Append("[UiControl(\"")
            .Append(EscapeString(control.PropertyName))
            .Append("\", UiControlType.")
            .Append(control.ControlType)
            .Append(", \"")
            .Append(EscapeString(control.LocatorValue))
            .Append("\"");

        if (control.LocatorKind != UiLocatorKind.AutomationId)
        {
            builder.Append(", LocatorKind = UiLocatorKind.")
                .Append(control.LocatorKind);
        }

        builder.Append(", FallbackToName = ")
            .Append(control.FallbackToName ? "true" : "false")
            .Append(")]");
        return builder.ToString();
    }

